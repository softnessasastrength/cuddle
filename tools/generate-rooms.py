#!/usr/bin/env python3
"""Validate the shared room catalog and emit the checked-in C tables."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def render():
    rooms = json.loads((ROOT / 'data/cuddle/rooms.json').read_text())['rooms']
    ids = set()
    lines = ['/* Generated by tools/generate-rooms.py; edit data/cuddle/rooms.json. */']
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    for i, room in enumerate(rooms):
        assert room['id'] not in ids and room['id'].replace('-', '').isalnum()
        ids.add(room['id'])
        assert room['kind'] in ('steps', 'touch', 'interest')
        assert (room['kind'] == 'touch') == (len(room['steps']) == 0)
        assert len(room['steps']) <= 32
        for j, step in enumerate(room['steps']):
            assert len(step['choices']) <= 6
            for c in step['choices']:
                assert -2 <= c['target'] < len(room['steps'])
                assert c['signal'] in (0, 1, 2, 4, 8, 16, 32)
                assert c['value'] in (0, 1, 2)
            if step['choices']:
                lines.append(f'static const struct cuddle_room_choice room_{i}_choices_{j}[] = {{')
                for c in step['choices']:
                    lines.append('  {' + f'{quote(c["label"])}, {c["target"]}, {c["signal"]}, {c["value"]}, {int(c.get("navigation", False))}' + '},')
                lines.append('};')
        if room['steps']:
            lines.append(f'static const struct cuddle_room_step room_{i}_steps[] = {{')
            for j, step in enumerate(room['steps']):
                choices = f'room_{i}_choices_{j}' if step['choices'] else 'NULL'
                lines.append('  {' + f'{quote(step["title"])}, {quote(step["body"])}, {choices}, {len(step["choices"])}, {int(step.get("record", False))}' + '},')
            lines.append('};')
    lines.append('static const struct cuddle_room k_rooms[] = {')
    for i, room in enumerate(rooms):
        steps = f'room_{i}_steps' if room['steps'] else 'NULL'
        kind = {'steps': 'CUDDLE_ROOM_STEPS', 'touch': 'CUDDLE_ROOM_TOUCH', 'interest': 'CUDDLE_ROOM_INTEREST'}[room['kind']]
        lines.append('  {' + f'{quote(room["id"])}, {quote(room["title"])}, {quote(room["summary"])}, {kind}, {steps}, {len(room["steps"])}' + '},')
    lines.append('};')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    target = ROOT / 'src/lib/rooms-data.inc'
    content = render()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Room tables are stale: run python3 tools/generate-rooms.py')
    else:
        target.write_text(content)
